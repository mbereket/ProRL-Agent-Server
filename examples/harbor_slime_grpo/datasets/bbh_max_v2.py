#!/usr/bin/env python3
"""Download bbh-max-v2 (bio-synth) as a directory of Harbor tasks.

TODO(remove): this script is redundant. The HF repo already stores the Harbor
layout, so staging is one command and prepare_tasks.py does the validation:

    hf download mbereket-nvidia/bio-synth-bbh-max-v2-train-v2 --repo-type dataset --local-dir <dir>

Delete it (and the tasks.dataset config hook) once the configs point tasks.dir
at a directory staged that way.

bbh-max-v2 is a set of 300 verified synthetic bioinformatics tasks generated by
the bio-synth pipeline (generate/bbh-max-v2) and published as a Hugging Face
dataset. Every task runs in one shared runtime image hosted on gitlab-master
(``bbh-max-v1-harbor-runtime``, private: the registry needs
APPTAINER_DOCKER_USERNAME/PASSWORD at pull time) and is graded by a python
verifier in ``tests/test.sh`` that writes 0/1 to /logs/verifier/reward.txt; no
LLM judge is involved.

The HF repo already stores the layout the pipeline consumes, so this script is a
snapshot download plus validation (no conversion):

    <output>/manifest.json           {"tasks": [{"directory": "task-0001", ...}, ...]}
    <output>/harbor/task-XXXX/
        instruction.md               the prompt the agent receives
        task.toml                    [environment] docker_image, [agent]/[verifier] timeouts
        tests/test.sh                verifier (hidden from the agent)
        environment/files/...        optional staging (setup.sh, data files)
    <output>/SOURCE.json             provenance written here: repo, commit sha, download time

Authentication: the repo is private; huggingface_hub reads HF_TOKEN or the
token saved by ``hf auth login``.

    python datasets/bbh_max_v2.py --output <dir>                       # main
    python datasets/bbh_max_v2.py --output <dir> --revision <sha>      # pinned commit
"""
from __future__ import annotations

import argparse
import json
import sys
import tomllib
from datetime import datetime, timezone
from pathlib import Path

DEFAULT_REPO = "mbereket-nvidia/bio-synth-bbh-max-v2-train-v2"
REQUIRED_FILES = ("instruction.md", "task.toml", "tests/test.sh")


def validate(output: Path) -> tuple[int, set[str]]:
    """Check the downloaded layout; return (task count, distinct docker images)."""
    manifest = output / "manifest.json"
    if not manifest.is_file():
        raise SystemExit(f"validation failed: {manifest} missing")
    entries = json.loads(manifest.read_text(encoding="utf-8")).get("tasks") or []
    if not entries:
        raise SystemExit(f"validation failed: {manifest} lists no tasks")
    problems: list[str] = []
    images: set[str] = set()
    for e in entries:
        task_dir = output / "harbor" / e["directory"]
        missing = [f for f in REQUIRED_FILES if not (task_dir / f).is_file()]
        if missing:
            problems.append(f"{e['directory']}: missing {', '.join(missing)}")
            continue
        try:
            with open(task_dir / "task.toml", "rb") as f:
                image = tomllib.load(f).get("environment", {}).get("docker_image")
        except tomllib.TOMLDecodeError as exc:
            problems.append(f"{e['directory']}: task.toml unreadable ({exc})")
            continue
        if not image:
            problems.append(f"{e['directory']}: task.toml has no [environment] docker_image")
            continue
        images.add(image)
    if problems:
        shown = "\n  ".join(problems[:20])
        more = f"\n  ... {len(problems) - 20} more" if len(problems) > 20 else ""
        raise SystemExit(f"validation failed ({len(problems)} tasks):\n  {shown}{more}")
    return len(entries), images


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", required=True, help="Task directory root to write (manifest.json + harbor/)")
    parser.add_argument("--repo", default=DEFAULT_REPO, help="HF dataset repo id")
    parser.add_argument("--revision", default="main", help="HF branch, tag or commit sha")
    parser.add_argument("--overwrite", action="store_true", help="Download into a non-empty output directory")
    opts = parser.parse_args()

    output = Path(opts.output).expanduser().resolve()
    if output.exists() and any(output.iterdir()) and not opts.overwrite:
        raise SystemExit(f"{output} exists and is not empty (use --overwrite)")
    output.mkdir(parents=True, exist_ok=True)

    from huggingface_hub import HfApi, get_token, snapshot_download
    from huggingface_hub.errors import GatedRepoError, RepositoryNotFoundError

    api = HfApi()
    try:
        info = api.dataset_info(opts.repo, revision=opts.revision)
    except (RepositoryNotFoundError, GatedRepoError) as exc:
        token_hint = "" if get_token() else " (no HF token found: set HF_TOKEN or run `hf auth login`)"
        raise SystemExit(f"cannot access dataset {opts.repo}@{opts.revision}: {exc}{token_hint}")
    print(f"downloading {opts.repo}@{opts.revision} ({info.sha}) -> {output}", file=sys.stderr)
    snapshot_download(opts.repo, repo_type="dataset", revision=info.sha, local_dir=str(output))

    count, images = validate(output)
    (output / "SOURCE.json").write_text(json.dumps({
        "repo": opts.repo,
        "revision": opts.revision,
        "sha": info.sha,
        "downloaded_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }, indent=2) + "\n", encoding="utf-8")
    print(f"docker images ({len(images)}):", file=sys.stderr)
    for image in sorted(images):
        print(f"  {image}", file=sys.stderr)
    print(f"{count} tasks -> {output}", file=sys.stderr)


if __name__ == "__main__":
    main()
